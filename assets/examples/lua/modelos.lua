local v=linblux.vec3
local a=linblux.scene.create("part",{name="Peça A",position=v(60,10,0),size=v(2,2,2)})
local b=linblux.scene.create("part",{name="Peça B",position=v(64,10,0),size=v(2,2,2)})
local model=linblux.scene.group({a,b},"Modelo programável")
assert(a.parent==model and b.parent==model)
assert(math.abs(model.position.x-62)<0.001)
model.position=v(72,10,0)
model.rotation=v(0,90,0)
model.scale=2
assert(math.abs(a.position.x-72)<0.001 and math.abs(a.position.z-4)<0.001)
local point=model:point_to_world(v(1,2,3))
local localPoint=model:point_to_local(point)
assert(math.abs(localPoint.x-1)<0.001 and math.abs(localPoint.z-3)<0.001)
local before=a.position
model:set_pivot({position=v(70,10,0)})
assert(math.abs(a.position.x-before.x)<0.001)
local reference=linblux.scene.create("model",{position=v(80,10,0),rotation=v(0,20,0),scale=2})
model:set_transform({position=v(1,0,0),rotation=v(0,45,0),scale=1},reference)
local relative=model:get_transform(reference)
assert(math.abs(relative.position.x-1)<0.001 and math.abs(relative.rotation.y-45)<0.001 and math.abs(relative.scale-1)<0.001)
local component=model:add_script("linblux.self:set_attribute('script_modelo',true)","Comportamento do modelo")
linblux.time.after(0.08,function()
    assert(model:get_attribute("script_modelo"))
    model:remove_component(component)
    local clone=model:clone()
    assert(clone.id~=model.id and #clone:children()==2)
    clone:destroy()
    local original=a.position
    model:ungroup()
    assert(not model.alive and a.alive and a.parent==linblux.scene.root)
    assert(math.abs(a.position.x-original.x)<0.001)
    reference:destroy()
    linblux.scene.root:set_attribute("modelos_concluido",true)
end)
