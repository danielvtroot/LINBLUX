#!/usr/bin/env python3
"""Compile the shared LINBLUX palette to C++ and RCSS. --check for CI."""
import json
from pathlib import Path
import sys
root=Path(__file__).resolve().parent.parent
p=json.loads((root/'assets/ui/theme.json').read_text())
cpp='#pragma once\n// Generated by scripts/generate-theme.py; edit assets/ui/theme.json.\n'
cpp+='inline constexpr Palette LinbluxPalette{\n'
for value in p.values():
 h=value.lstrip('#');rgba=[int(h[i:i+2],16)/255 for i in range(0,len(h),2)]
 if len(rgba)==3:rgba.append(1.)
 cpp+='    {'+','.join(f'{v:.6f}f' for v in rgba)+'},\n'
cpp+='};\n'
css='/* Generated shared LINBLUX theme. */\n'
css+=f"button:hover {{ background-color: {p['hover']}; border-color: {p['accent']}; }}\n"
css+=f"button:active, button.active, select option:hover, select option:checked {{ background-color: {p['selected']}; border-color: {p['accent']}; }}\n"
css+=f"button.primary, .experience-primary {{ background-color: #ba2838; border-color: {p['accent']}; }}\n"
css+=f"button:focus, input:focus, textarea:focus, select:focus {{ border-color: {p['accent']}; }}\n"
css+=f"#header, #tabs, #ribbon, #status {{ background-color: {p['background']}; }}\n"
css+=f".panel, #advanced, #dialog, #context-menu {{ background-color: {p['panel']}; border-color: {p['border']}; }}\n"
css+=f".panel-heading, .document-tab, .group-name {{ background-color: {p['raised']}; }}\n"
css+=f"input[type=checkbox]:checked {{ background-color: {p['accent']}; decorator: none; }}\n"
css+=f".tree-row.selected, .tree-row:hover, .document-tab.active, #tabs button.active {{ background-color: {p['selected']}; border-color: {p['accent']}; }}\n"
css+=f"#game-topbar .logo-button, #game-capsule {{ border-radius: 8px; background-color: {p['panel']}; }}\n"
css+=f".pause-panel {{ background-color: {p['panel']}; border-color: {p['border']}; }}\n"
css+=f".pause-tabs button.active {{ border-color: {p['accent']}; }}\n"
css+='.pause-tabs button { border-radius: 6px; }\n'
css+='#game-topbar button { border-radius: 7px; }\n'
outputs={root/'src/editor/StudioPalette.generated.h':cpp,root/'assets/ui/styles/theme.rcss':css}
for path,text in outputs.items():
 if '--check' in sys.argv:
  if not path.exists() or path.read_text()!=text:raise SystemExit(f'Tema desatualizado: {path}')
 else:path.write_text(text)
